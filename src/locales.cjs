function resolveLanguage(setting, systemLocale) {
  if (setting === 'tr' || setting === 'en') return setting;
  return String(systemLocale || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

function strings(language) {
  return language === 'tr' ? tr : en;
}

function format(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (key in values ? values[key] : `{${key}}`));
}

module.exports = { tr, en, resolveLanguage, strings, format };
